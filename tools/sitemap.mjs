#!/usr/bin/env node
// Writes the site's two static, generated pages from data/site.js (no JavaScript or 3D needed to read them):
//   sitemap/index.html  every page and every posted essay
//   keys/index.html     The Key: the log of the site's symbols (data/site.js `symbols`)
// so nothing on the site can block reading. Each essay links both to its
// build page and to its plain-text fragment in content/ (readable even with JS off).
// Run after posting an essay or changing data/site.js (incl. a symbol's meaning):   node tools/sitemap.mjs
import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { site, members, builds, symbols = [] } = await import(path.join(ROOT, "data/site.js"));
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const nameOf = (id) => (id === "team" ? "Team Dolores" : members.find((m) => m.id === id)?.name || id);
const TODAY = new Date().toISOString().slice(0, 10);

const pages = [["Home", "../index.html"], ["Hosts", "../team/index.html"], ["Essays", "../essays/index.html"], ["The Chasm (sources)", "../sources/index.html"]];
if (symbols.length) pages.push(["The Key: what the symbols mean", "../keys/index.html"]);

const buildList = builds.map((b) => {
  const posted = Object.entries(b.entries).filter(([, e]) => e.status === "reached");
  const state = posted.length ? "" : b.status === "near" ? " (near)" : b.due && b.due < TODAY ? " (being posted)" : " (locked)";
  return `      <li><h3><a href="../essays/build-${b.n}/index.html">${b.title ? `${esc(b.title)} (Build ${b.n})` : `Build ${b.n}`}</a>${b.theme ? `: ${esc(b.theme)}` : ""}${state}</h3>
        ${posted.length ? `<ul>${posted.map(([id, e]) => `
          <li>${esc(nameOf(id))}${e.title ? `, <i>${esc(e.title)}</i>` : ""}: <a href="../essays/build-${b.n}/index.html#${id}">read on the site</a> · <a href="../${e.file}">plain text</a></li>`).join("")}
        </ul>` : ""}
      </li>`;
}).join("\n");

const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Sitemap · ${esc(site.team)}</title>
  <meta name="description" content="Every page and every essay on the ${esc(site.team)} site, as plain links.">
  <link rel="icon" href="data:,">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="../css/tokens.css">
  <link rel="stylesheet" href="../css/site.css">
</head>
<body data-page="sitemap">
  <!-- generated by tools/sitemap.mjs from data/site.js; works with JavaScript and 3D off -->
  <a class="skip-link" href="#main">Skip to main content</a>
  <header class="site-header"><div class="wrap"><a class="brand" href="../index.html"><span class="brand-name">${esc(site.team)}</span><span class="label">HONORS 241 // Westworld × Plutarch</span></a></div></header>
  <main id="main" class="wrap page sitemap">
    <p class="label">Delos archive // plain index</p>
    <h1>Sitemap</h1>
    <p class="lede">Every page and every posted essay, as plain links. Nothing here needs JavaScript or 3D.</p>
    <section class="section"><h2>Pages</h2>
      <ul>${pages.map(([t, h]) => `<li><a href="${h}">${esc(t)}</a></li>`).join("")}</ul>
    </section>
    <section class="section"><h2>Essays by build</h2>
      <ol class="sitemap-builds">
${buildList}
      </ol>
    </section>
    <section class="section"><h2>Hosts</h2>
      <ul>${members.map((m) => `<li><a href="../members/${m.id}.html">${esc(m.name)}</a></li>`).join("")}</ul>
    </section>${symbols.length ? `
    <section class="section"><h2>The Key</h2>
      <ul>${symbols.map((s) => `<li><a href="../keys/index.html#key-${s.number}">KEY ${s.number}: ${esc(s.name)}</a></li>`).join("")}</ul>
    </section>` : ""}
  </main>
  <footer class="site-footer"><div class="wrap"><p>Thank you to ${esc(site.professor)} and our GSI, ${esc(site.gsi)}.</p></div></footer>
</body>
</html>
`;
mkdirSync(path.join(ROOT, "sitemap"), { recursive: true });
writeFileSync(path.join(ROOT, "sitemap/index.html"), html);
console.log("wrote sitemap/index.html:", builds.reduce((n, b) => n + Object.values(b.entries).filter((e) => e.status === "reached").length, 0), "essays");

/* ---------- The Key ---------- */
const anchor = (n) => (n === "Team" ? "team" : n.toLowerCase());
const card = (k) => `
      <article class="key-card" id="key-${k.number}" aria-labelledby="key-${k.number}-h">
        <p class="label">KEY ${k.number}</p>
        <h2 id="key-${k.number}-h">${esc(k.name)}</h2>
        <dl class="key-facts">
          <div><dt>On the site</dt><dd>${k.onSite.map((o) => `<a href="../${o.href}">${esc(o.label)}</a>`).join(" · ")}</dd></div>
          <div><dt>Westworld</dt><dd>${k.westworld ? esc(k.westworld) : "—"}</dd></div>
          <div><dt>Plutarch</dt><dd>${k.plutarch.length ? "pp. " + k.plutarch.map(esc).join(", ") : "—"}</dd></div>
          <div class="wide"><dt>Builds</dt><dd>${k.builds.length ? k.builds.map((b) => `<span class="key-build">Build ${b.n}: ${b.members.map((m) => `<a href="../essays/build-${b.n}/index.html#${anchor(m)}">${esc(m)}</a>`).join(", ")}</span>`).join("") : "No essay discusses it yet."}</dd></div>
        </dl>
        <div class="key-meaning">${k.meaning
          ? `<p>${esc(k.meaning)}</p>`
          : `<p class="await">AWAITING ANNOTATION // TEAM DOLORES</p>${k.note ? `<p class="key-note"><span class="label">Note for the team</span> ${esc(k.note)}</p>` : ""}`}</div>
      </article>`;
const keysHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>The Key · ${esc(site.team)}</title>
  <meta name="description" content="The Key: a running log of every symbol on the ${esc(site.team)} site and what it means.">
  <link rel="icon" href="data:,">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="../css/tokens.css">
  <link rel="stylesheet" href="../css/site.css">
  <script type="module" src="../js/site.js"></script>
</head>
<body data-page="keys">
  <!-- generated by tools/sitemap.mjs from data/site.js symbols; readable with JavaScript off -->
  <a class="skip-link" href="#main">Skip to main content</a>
  <header class="site-header" id="site-header"><div class="wrap"><a class="brand" href="../index.html"><span class="brand-name">${esc(site.team)}</span><span class="label">HONORS 241 // Westworld × Plutarch</span></a></div></header>
  <main id="main" class="wrap page keys">
    <p class="label">Delos archive // symbol log</p>
    <h1>The Key</h1>
    <p class="lede">A running log of the symbols on this site: where each one appears, what it points to in Westworld (Season 1) and in Plutarch, and which builds take it up. The meanings are written by the team.</p>
    <div class="key-list">${symbols.map(card).join("")}
    </div>
  </main>
  <footer class="site-footer" id="site-footer"><div class="wrap"><p><a href="../sitemap/index.html">Sitemap: every page and essay</a></p></div></footer>
</body>
</html>
`;
if (symbols.length) {
  mkdirSync(path.join(ROOT, "keys"), { recursive: true });
  writeFileSync(path.join(ROOT, "keys/index.html"), keysHtml);
  console.log("wrote keys/index.html:", symbols.length, "symbols,", symbols.filter((k) => !k.meaning).length, "awaiting annotation");
}
