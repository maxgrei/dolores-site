#!/usr/bin/env node
// Writes sitemap/index.html: a plain, static index of every page and every posted essay that needs
// no JavaScript and no 3D, so nothing on the site can block reading. Each essay links both to its
// build page and to its plain-text fragment in content/ (readable even with JS off).
// Run after posting an essay or changing data/site.js:   node tools/sitemap.mjs
import { writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { site, members, builds, symbols = [] } = await import(path.join(ROOT, "data/site.js"));
const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const nameOf = (id) => (id === "team" ? "Team Dolores" : members.find((m) => m.id === id)?.name || id);
const TODAY = new Date().toISOString().slice(0, 10);

const pages = [["Home", "../index.html"], ["Hosts", "../team/index.html"], ["Essays", "../essays/index.html"], ["The Chasm (sources)", "../sources/index.html"]];
if (existsSync(path.join(ROOT, "keys/index.html"))) pages.push(["The Key: what the symbols mean", "../keys/index.html"]);

const buildList = builds.map((b) => {
  const posted = Object.entries(b.entries).filter(([, e]) => e.status === "reached");
  const state = posted.length ? "" : b.status === "near" ? " (near)" : b.due && b.due < TODAY ? " (being posted)" : " (locked)";
  return `      <li><h3><a href="../essays/build-${b.n}/index.html">Build ${b.n}</a>${b.theme ? `: ${esc(b.theme)}` : ""}${state}</h3>
        ${posted.length ? `<ul>${posted.map(([id, e]) => `
          <li>${esc(nameOf(id))}${e.title ? `, <i>${esc(e.title)}</i>` : ""}: <a href="../essays/build-${b.n}/index.html#${id}">read on the site</a> · <a href="../${e.file}">plain text</a></li>`).join("")}
        </ul>` : ""}
      </li>`;
}).join("\n");

const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Sitemap · ${esc(site.team)}</title>
  <meta name="description" content="Every page and every essay on the ${esc(site.team)} site, as plain links.">
  <link rel="icon" href="data:,">
  <link rel="stylesheet" href="../css/tokens.css">
  <link rel="stylesheet" href="../css/site.css">
</head>
<body data-page="sitemap">
  <!-- generated by tools/sitemap.mjs from data/site.js; works with JavaScript and 3D off -->
  <a class="skip-link" href="#main">Skip to main content</a>
  <header class="site-header"><div class="wrap"><a class="brand" href="../index.html"><span class="brand-name">${esc(site.team)}</span><span class="label">HONORS 241 // Westworld × Plutarch</span></a></div></header>
  <main id="main" class="wrap page sitemap">
    <p class="label">Delos archive // plain index</p>
    <h1>Sitemap</h1>
    <p class="lede">Every page and every posted essay, as plain links. Nothing here needs JavaScript or 3D.</p>
    <section class="section"><h2>Pages</h2>
      <ul>${pages.map(([t, h]) => `<li><a href="${h}">${esc(t)}</a></li>`).join("")}</ul>
    </section>
    <section class="section"><h2>Essays by build</h2>
      <ol class="sitemap-builds">
${buildList}
      </ol>
    </section>
    <section class="section"><h2>Hosts</h2>
      <ul>${members.map((m) => `<li><a href="../members/${m.id}.html">${esc(m.name)}</a></li>`).join("")}</ul>
    </section>${symbols.length ? `
    <section class="section"><h2>The Key</h2>
      <ul>${symbols.map((s) => `<li><a href="../keys/index.html#key-${s.number}">KEY ${s.number}: ${esc(s.name)}</a></li>`).join("")}</ul>
    </section>` : ""}
  </main>
  <footer class="site-footer"><div class="wrap"><p>Thank you to ${esc(site.professor)} and our GSI, ${esc(site.gsi)}.</p></div></footer>
</body>
</html>
`;
mkdirSync(path.join(ROOT, "sitemap"), { recursive: true });
writeFileSync(path.join(ROOT, "sitemap/index.html"), html);
console.log("wrote sitemap/index.html:", builds.reduce((n, b) => n + Object.values(b.entries).filter((e) => e.status === "reached").length, 0), "essays");
